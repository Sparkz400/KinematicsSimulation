"""Writes THIRD-PARTY-LICENSES.md from `cargo metadata`: every crate in Cargo.lock that a Windows or Linux build
uses, with its licence as its manifest states it. Run from the workspace root after a dependency change:

    python tools/third_party_licenses.py

Exits non-zero when a licence is missing or GPL/LGPL/AGPL, so a new dependency cannot slip in unseen.
"""
import json, subprocess, sys
from collections import defaultdict

TARGETS = ["x86_64-pc-windows-msvc", "x86_64-unknown-linux-gnu"]


crates, members = {}, set()
for target in TARGETS:
    meta = json.loads(subprocess.run(["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", target],
                                     check=True, capture_output=True, text=True, encoding="utf-8").stdout)
    members |= set(meta["workspace_members"])
    # Only what the resolver actually reaches for this target, not every package of the lock file.
    reached = {node["id"] for node in meta["resolve"]["nodes"]}
    for p in meta["packages"]:
        if p["id"] in reached and p["id"] not in members:
            crates[(p["name"], p["version"])] = (p.get("license") or p.get("license_file") and f"see {p['license_file']}" or "UNKNOWN", p.get("repository") or "")

by_licence = defaultdict(list)
for (name, version), (licence, _) in crates.items():
    by_licence[licence].append(f"{name} {version}")
# "GPL" covers LGPL and AGPL; a GPL offered as one choice of an OR (self_cell) is fine, any other is flagged.
flagged = [l for l in by_licence if l == "UNKNOWN" or l.startswith("see ") or ("GPL" in l and " OR " not in l)]
assert ("GPL" in "LGPL-2.1-or-later" and " OR " not in "LGPL-2.1-or-later") and " OR " in "Apache-2.0 OR GPL-2.0-only"

out = ["# Third-party licences", "",
       f"Generated by `tools/third_party_licenses.py` from `cargo metadata` ({', '.join(TARGETS)}). "
       f"{len(crates)} crates. The licence is the SPDX expression of each crate's manifest; where it offers a choice "
       "(`MIT OR Apache-2.0`), this project uses the crates under MIT or Apache-2.0.", "",
       "## MPL-2.0", "",
       "Crates under the Mozilla Public License 2.0 (`async-opcua` and its parts, used by `sim-opcua`) are file-level "
       "copyleft. Distributing a binary that contains them is allowed under any licence for the binary as a whole, "
       "provided that (a) recipients are told how to get the source code of the MPL-covered files (they are the "
       "unmodified crates on crates.io, at the versions listed below), and (b) any change to an MPL-covered file is "
       "published under the MPL. The project's own code stays under MIT OR Apache-2.0.", "",
       "## Other licences that ask for something", "",
       "- `self_cell` is `Apache-2.0 OR GPL-2.0-only`: used under Apache-2.0. No crate is used under a GPL or LGPL.",
       "- `epaint_default_fonts` (the app's built-in fonts) carries `OFL-1.1` and `Ubuntu-font-1.0`: the fonts may be "
       "bundled and redistributed with the program, not sold on their own; their licence texts go with the source package.",
       "- `Unicode-3.0` (ICU4X data, `unicode-ident`): the copyright and permission notice must accompany the data; it is "
       "in each crate's source package.",
       "- `BSL-1.0`, `Zlib`, `ISC`, `BSD-*`, `MIT-0`, `CC0-1.0`, `Unlicense`: permissive; BSL-1.0 needs no notice in binaries.", "",
       "## Summary", "", "| licence | crates |", "| --- | --- |"]
out += [f"| {l} | {len(v)} |" for l, v in sorted(by_licence.items(), key=lambda kv: -len(kv[1]))]
out += ["", "## Crates", "", "| crate | version | licence | source |", "| --- | --- | --- | --- |"]
out += [f"| {n} | {v} | {crates[(n, v)][0]} | {crates[(n, v)][1]} |" for n, v in sorted(crates)]
out += ["", "The full licence texts are in each crate's source package on crates.io (`cargo vendor` collects them).", ""]
open("THIRD-PARTY-LICENSES.md", "w", encoding="utf-8", newline="\n").write("\n".join(out))
print(f"{len(crates)} crates, {len(by_licence)} licence expressions")
for l in flagged:
    print("FLAGGED:", l, "->", ", ".join(by_licence[l]))
sys.exit(1 if flagged else 0)
