"""Fetches the Siemens data sheet of every motor in catalog/siemens/motors_s120.csv and writes the
values the catalogue lacks (limits, physical constants) as motors_s120_electrical.csv into <out folder>.

    python tools/catalog.py extract fetch_siemens_datasheets <folder for the downloaded PDFs> [cached]
    (or directly: python fetch_siemens_datasheets.py <folder for the downloaded PDFs> <out folder> [cached])

The service is slow and a full run takes hours. With `cached` the script fetches nothing and writes the
file from the data sheets already in the folder.

Siemens generates a data sheet per full article number. The electrical data depends only on the
winding, so the script completes each article number with common options (encoder, shaft, brake)
and takes the first combination the service knows. Needs pdftotext (xpdf 4.x) on the path.
Downloaded PDFs are kept in the folder and not fetched twice.
"""
import csv
import re
import subprocess
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

URL = "https://apim.industry.siemens.cloud/ted/datasheet?format=pdf&mlfbs={}&language=en&caller=SIOS"
# Endings to try: flange/DRIVE-CLiQ digit, then "-1", encoder, shaft and brake, degree of protection.
ENDINGS = {"1FK701": ["1-1JA3", "1-1AH3", "1-1AG3", "1-1JG3"],
           "1FK7": ["1-1CH0", "1-1CG0", "1-1CB0", "1-1CA0"],
           "1FT7": ["1-1CG0", "1-1CB0", "1-1CA0", "1-1CH1", "1-1CH0", "0-1CG0", "0-1CB0", "1-1CG1", "1-1CB1", "1-1NG1", "1-1NB1"]}
# Label on the data sheet -> column. The value is the first number after the label.
FIELDS = [("Number of poles", "poles"), ("Static torque (60 K)", "static_torque_60k_nm"), ("Stall current (60 K)", "stall_current_60k_a"),
          ("Max. permissible speed (mech.)", "max_speed_mechanical_rpm"), ("Max. permissible speed (inverter)", "max_speed_inverter_rpm"),
          ("Maximum torque", "max_torque_nm"), ("Maximum current", "max_current_a"), ("Torque constant", "torque_constant_nm_a"),
          ("Voltage constant at 20", "voltage_constant_v_per_1000rpm"), ("Winding resistance at 20", "winding_resistance_20c_ohm"),
          ("field inductance", "inductance_mh"), ("Electrical time constant", "electrical_time_constant_ms"),
          ("Mechanical time constant", "mechanical_time_constant_ms"), ("Thermal time constant", "thermal_time_constant_min"),
          ("Shaft torsional stiffness", "shaft_torsional_stiffness_nm_rad")]
HEADER = ["article", "data_sheet_article"] + [c for _, c in FIELDS]


def fetch(stem, folder, cached_only=False):
    """The data sheet PDF of the first full article number the service knows, and that number."""
    for known in folder.glob(stem + "*.pdf"):
        return known, known.stem
    if cached_only:
        return None, None
    endings = next(e for prefix, e in ENDINGS.items() if stem.startswith(prefix))
    for attempt in range(2):  # the service answers 404 now and then for numbers it knows
        for ending in endings:
            article = stem + ending
            request = urllib.request.Request(URL.format(article), headers={"User-Agent": "Mozilla/5.0"})
            try:
                with urllib.request.urlopen(request, timeout=60) as answer:
                    data = answer.read()
            except (urllib.error.URLError, TimeoutError):
                data = b""
            time.sleep(0.5)
            if data.startswith(b"%PDF"):
                path = folder / (article + ".pdf")
                path.write_bytes(data)
                return path, article
    return None, None


def values(pdf):
    text = subprocess.run(["pdftotext", "-q", "-table", "-enc", "UTF-8", str(pdf), "-"], capture_output=True).stdout.decode("utf-8", "replace")
    text = re.sub(r"[ \t]+", " ", text)
    out = {}
    for label, column in FIELDS:
        found = re.search(re.escape(label) + r"[^\d\n]*?(\d[\d,]*(?:\.\d+)?)\s", text)
        out[column] = found.group(1).replace(",", "") if found else ""
    return out


def main():
    folder, catalog = Path(sys.argv[1]), Path(sys.argv[2])
    folder.mkdir(parents=True, exist_ok=True)
    motors = Path(__file__).resolve().parents[1] / "siemens" / "motors_s120.csv"
    lines = [l for l in motors.read_text(encoding="utf-8").splitlines() if not l.startswith("#")]
    rows, missing = [], []
    for motor in csv.DictReader(lines):
        part = motor["part_number"]
        pdf, article = fetch(part, folder, cached_only=sys.argv[3:] == ["cached"])
        if not pdf:
            missing.append(part)
            continue
        found = values(pdf)
        rows.append([part, article] + [found[c] for _, c in FIELDS])
    notes = """# Source: the Siemens data sheet of each motor, generated by Siemens' data sheet service
# (apim.industry.siemens.cloud/ted/datasheet) for the full article number in data_sheet_article.
# Extracted by catalog/tools/fetch_siemens_datasheets.py; the numbers are Siemens', the layout is ours.
# One row per motor of motors_s120.csv whose data sheet has been fetched, by the same article key. The options in the full article number
# (encoder, shaft, brake) do not change these values.
# poles: number of poles (twice the pole pairs). torque_constant: at a winding temperature rise of 100 K.
# voltage_constant: at 20 degC, line to line, RMS, per 1000 rpm. winding_resistance: of one phase at 20 degC.
# inductance: rotating field inductance. max_speed_inverter: what the DC link voltage allows.
# An empty field: the data sheet does not state the value.
# The data sheets give the sixteen 1FT7 High Dynamic motors 6 poles; the catalogue table in motors_s120.csv gives
#   them 5 pole pairs. Both files keep what their source prints.
# The service has no data sheet for the 1FK7022-5AK7 under any article number tried.
# Kept as printed although it does not fit: voltage_constant of the 1FT7044-1AF7 is 49.0, less than half of what
#   its torque constant of 1.79 N m/A implies.
"""
    (catalog / "motors_s120_electrical.csv").write_text(notes + ",".join(HEADER) + "\n" + "".join(",".join(r) + "\n" for r in rows),
                                                       encoding="utf-8", newline="\n")
    print(f"{len(rows)} data sheets read, {len(missing)} not found: {' '.join(missing)}")


if __name__ == "__main__":
    main()
